# --------------------------------------------------------------------------- constants

#: Statuses that record an *absence* of enacted work. Declared here, not imported, so the
#: oracle is independent of the set the subject classifies against (I-7).
ABSENCE_STATUSES: Final[tuple[str, ...]] = (
    "",
    "blocked",
    "deferred",
    "failed",
    "no_result",
    "rejected",
    "skipped",
    "unknown",
    "withheld",
)

#: Statuses an agent returns when it did enact its ratified proposal. ``ok`` is the shape
#: ``orchestrator/tests/consensus/test_dispatch_choke_point.py:222`` observes on a real
#: dispatch; the rest are the same class of report.
ENACTED_STATUSES: Final[tuple[str, ...]] = (
    "actuated",
    "applied",
    "completed",
    "confirmed",
    "executed",
    "ok",
    "success",
)

#: Generated by neither pool - see the module docstring. ``diverged`` is an open
#: cross-cutting question owned by ``escalation.py``, not a claim this property makes.
UNCLASSIFIED_STATUSES: Final[tuple[str, ...]] = ("diverged",)

#: The prefix ``_phase_execute`` writes when the execution hop raised.
ERROR_PREFIX: Final[str] = "error:"

#: I-5 is stated without qualification, so no assertion here may depend on the route.
TIERS: Final[tuple[DecisionTier, ...]] = tuple(DecisionTier)

#: Every configurable fallback, including the two whose names imply execution.
TIMEOUT_ACTIONS: Final[tuple[HitlTimeoutAction, ...]] = tuple(HitlTimeoutAction)

#: The shipped HITL bound, read from configuration. No seconds literal appears below.
DEFAULT_TIMEOUT_SECONDS: Final[float] = OrchestratorConfig().hitl_timeout_seconds

#: Event-loop turns allowed for every escalation to register its pending entry, and for
#: one released escalation to finish. A turn bound rather than a wall-clock watchdog: a
#: regression fails the example instead of sleeping on it (I-0).
MAX_SCHEDULER_TURNS: Final[int] = 16

#: Alphabet for generated free text (exception details, operator notes). ASCII only.
DETAIL_ALPHABET: Final[str] = "abcdefghijklmnopqrstuvwxyz -_"

#: Identifier space for generated decision ids. ``UUID(int=n)`` keeps examples
#: reproducible where ``uuid4`` would not.
ID_SPACE: Final[int] = 2**32


# ------------------------------------------------------------------------ generated data


class Evidence(NamedTuple):
    """Generated ``execution_confirmations`` plus what they mean by construction."""

    entries: tuple[str, ...]
    #: True iff at least one entry was drawn from ``ENACTED_STATUSES``.
    enacted: bool


class Outstanding(NamedTuple):
    """One escalation awaiting resolution, and how it is scripted to resolve."""

    decision: ConsensusDecision
    enacted: bool
    times_out: bool
    response: dict[str, Any]


class EscalationCase(NamedTuple):
    """Concurrently outstanding escalations, a configuration, and a resolution order."""

    settings: OrchestratorConfig
    escalations: tuple[Outstanding, ...]
    order: tuple[UUID, ...]


# ------------------------------------------------------------------------ observations


class Resolution(NamedTuple):
    """What was observable around one escalation's resolution."""

    decision_id: UUID
    timed_out: bool
    result: ConsensusDecision | None
    pending_before: frozenset[UUID]
    pending_after: frozenset[UUID]
    #: Identifiers not yet resolved once this one has been.
    still_outstanding: frozenset[UUID]
    #: Other escalations whose task had completed at this point ...
    completed_others: frozenset[UUID]
    #: ... and the only ones that legitimately could have: those resolved earlier.
    expected_completed_others: frozenset[UUID]
    #: Whether the human response was accepted (``None`` for a timed-out resolution).
    response_accepted: bool | None
    #: Whether a *second* response to the same identifier was accepted after resolution.
    late_response_accepted: bool


class DriveReport(NamedTuple):
    """Everything one driven case observed, asserted by the properties below."""

    registered: frozenset[UUID]
    resolutions: tuple[Resolution, ...]
    pending_at_end: tuple[UUID, ...]
    #: ``(kafka key, decision_id in the published payload)`` per escalation.
    published: tuple[tuple[str, str], ...]
    #: The bound handed to the waiter for each escalation - reported, never awaited.
    reported_bounds: tuple[float, ...]


# ------------------------------------------------------------------------- test doubles


class RecordingProducer:
    """A Kafka producer stand-in: records what was published and publishes nothing."""

    __slots__ = ("published",)

    def __init__(self) -> None:
        self.published: list[tuple[str, str]] = []

    def produce(self, topic: str, *, value: dict[str, Any], key: str) -> None:
        del topic
        self.published.append((key, str(value.get("decision_id", ""))))


class GatedWaiter:
    """The ``HumanResponseWaiter`` seam, driven by events instead of by a clock.

    Identifiers in *timeout_for* raise ``TimeoutError``, but only once the driver releases
    them, so *when* a timeout lands relative to a human response is generated rather than
    raced. ``timeout`` is recorded and never slept on.
    """

    __slots__ = ("_gates", "_timeout_for", "reported_bounds")

    def __init__(self, timeout_for: frozenset[UUID]) -> None:
        self._timeout_for: frozenset[UUID] = timeout_for
        self._gates: dict[UUID, asyncio.Event] = {}
        self.reported_bounds: list[float] = []

    def _gate(self, decision_id: UUID) -> asyncio.Event:
        gate = self._gates.get(decision_id)
        if gate is None:
            gate = asyncio.Event()
            self._gates[decision_id] = gate
        return gate

    def release(self, decision_id: UUID) -> None:
        """Let the escalation for *decision_id* time out now."""
        self._gate(decision_id).set()

    async def __call__(
        self,
        future: asyncio.Future[dict[str, Any]],
        *,
        timeout: float,
        decision_id: UUID,
    ) -> dict[str, Any]:
        self.reported_bounds.append(timeout)
        if decision_id in self._timeout_for:
            await self._gate(decision_id).wait()
            raise TimeoutError
        return await future


# --------------------------------------------------------------------------- strategies


def varied(draw: st.DrawFn, status: str) -> str:
    """Case- and whitespace-vary *status*: the classifier strips and lowercases."""
    lead = draw(st.sampled_from(("", " ", "\t")))
    trail = draw(st.sampled_from(("", " ", "\n")))
    body = status.upper() if draw(st.booleans()) else status
    return f"{lead}{body}{trail}"


@st.composite
def absence_entries(draw: st.DrawFn) -> str:
    """One confirmation entry that records an absence of enacted work."""
    if draw(st.booleans()):
        return varied(draw, draw(st.sampled_from(ABSENCE_STATUSES)))
    detail = draw(st.text(alphabet=DETAIL_ALPHABET, max_size=12))
    return varied(draw, f"{ERROR_PREFIX}{detail}")


@st.composite
def enacted_entries(draw: st.DrawFn) -> str:
    """One confirmation entry that names work an agent actually enacted."""
    return varied(draw, draw(st.sampled_from(ENACTED_STATUSES)))


@st.composite
def evidence(draw: st.DrawFn) -> Evidence:
    """Confirmations whose meaning is known from the pool each entry came from."""
    absences = draw(st.lists(absence_entries(), max_size=3))
    enacted = draw(st.lists(enacted_entries(), max_size=2))
    entries = draw(st.permutations([*absences, *enacted]))
    return Evidence(entries=tuple(entries), enacted=bool(enacted))


def timeout_actions() -> st.SearchStrategy[HitlTimeoutAction]:
    """Every configurable timeout fallback, including the two that imply execution."""
    return st.sampled_from(TIMEOUT_ACTIONS)


def configured_bounds() -> st.SearchStrategy[float]:
    """Bounds derived from the configured default - the shipped value plus a spread."""
    return st.one_of(
        st.just(DEFAULT_TIMEOUT_SECONDS),
        st.floats(
            min_value=DEFAULT_TIMEOUT_SECONDS / 100.0,
            max_value=DEFAULT_TIMEOUT_SECONDS * 10.0,
            allow_nan=False,
            allow_infinity=False,
        ),
    )


@st.composite
def hitl_settings(draw: st.DrawFn) -> OrchestratorConfig:
    """Configuration carrying the HITL bound and fallback the escalator is built with."""
    return OrchestratorConfig(
        hitl_timeout_seconds=draw(configured_bounds()),
        hitl_timeout_action=str(draw(timeout_actions()).value),
    )


def confidences() -> st.SearchStrategy[float]:
    """Any confidence a ``ConsensusDecision`` admits (the model pins ``0 <= c <= 1``)."""
    return st.floats(min_value=0.0, max_value=1.0, allow_nan=False, allow_infinity=False)


def human_responses() -> st.SearchStrategy[dict[str, Any]]:
    """What a human sends: an approval, a rejection, or a modification."""
    return st.fixed_dictionaries(
        {"action": st.sampled_from(("approved", "rejected", "modified"))},
        optional={"notes": st.text(alphabet=DETAIL_ALPHABET, max_size=12)},
    )


def outstanding_decision(
    decision_id: UUID,
    tier: DecisionTier,
    confidence: float,
    confirmations: Sequence[str],
) -> ConsensusDecision:
    """A decision carrying exactly the generated confirmations and no other evidence."""
    return ConsensusDecision(
        decision_id=decision_id,
        tier=tier,
        proposals=[],
        selected_action={},
        pareto_weights={"demand_accuracy": 1.0},
        confidence=confidence,
        audit_trace=["property-25"],
        execution_confirmations=list(confirmations),
    )


@st.composite
def escalation_cases(draw: st.DrawFn) -> EscalationCase:
    """Two to four concurrent escalations, at least one of which times out.

    R5.9 is about what happens *while* escalations are outstanding together, so a case is
    never a single escalation. The resolution order is a generated permutation, which is
    what makes "resolving one never resolves another" falsifiable in both directions.
    """
    settings = draw(hitl_settings())
    raw_ids = draw(
        st.lists(
            st.integers(min_value=1, max_value=ID_SPACE),
            min_size=2,
            max_size=4,
            unique=True,
        ),
    )
    identifiers = [UUID(int=raw) for raw in raw_ids]

    shuffled = draw(st.permutations(identifiers))
    timing_out = frozenset(shuffled[: draw(st.integers(min_value=1, max_value=len(identifiers)))])

    escalations: list[Outstanding] = []
    for decision_id in identifiers:
        found = draw(evidence())
        escalations.append(
            Outstanding(
                decision=outstanding_decision(
                    decision_id,
                    draw(st.sampled_from(TIERS)),
                    draw(confidences()),
                    found.entries,
                ),
                enacted=found.enacted,
                times_out=decision_id in timing_out,
                response=draw(human_responses()),
            ),
        )

    return EscalationCase(
        settings=settings,
        escalations=tuple(escalations),
        order=tuple(draw(st.permutations(identifiers))),
    )


# ------------------------------------------------------------------------------- driver


async def settle(task: asyncio.Task[ConsensusDecision]) -> ConsensusDecision | None:
    """Let *task* finish using scheduler turns only - never the clock.

    Returns ``None`` when the escalation did not finish within the bound, so a hang
    surfaces as a failed assertion in the property rather than as a stalled test run.
    """
    for _ in range(MAX_SCHEDULER_TURNS):
        if task.done():
            return await task
        await asyncio.sleep(0)
    task.cancel()
    return None


async def drive(case: EscalationCase) -> DriveReport:
    """Escalate every decision, resolve them in the generated order, observe as we go."""
    waiter = GatedWaiter(
        frozenset(entry.decision.decision_id for entry in case.escalations if entry.times_out),
    )
    producer = RecordingProducer()
    escalator = HITLEscalation(
        kafka_producer=producer,
        ws_manager=WebSocketManager(),
        timeout_seconds=case.settings.hitl_timeout_seconds,
        timeout_action=case.settings.hitl_timeout_action,
        waiter=waiter,
    )

    by_id = {entry.decision.decision_id: entry for entry in case.escalations}
    tasks: dict[UUID, asyncio.Task[ConsensusDecision]] = {
        entry.decision.decision_id: asyncio.create_task(escalator.escalate(entry.decision))
        for entry in case.escalations
    }

    # Every escalation registers its pending entry before the first resolution.
    for _ in range(MAX_SCHEDULER_TURNS):
        if len(escalator.pending_decision_ids()) == len(tasks):
            break
        await asyncio.sleep(0)
    registered = frozenset(escalator.pending_decision_ids())

    all_ids = frozenset(tasks)
    resolved: set[UUID] = set()
    resolutions: list[Resolution] = []

    for decision_id in case.order:
        entry = by_id[decision_id]
        pending_before = frozenset(escalator.pending_decision_ids())

        accepted: bool | None = None
        if entry.times_out:
            waiter.release(decision_id)
        else:
            accepted = await escalator.receive_human_response(decision_id, dict(entry.response))

        result = await settle(tasks[decision_id])
        pending_after = frozenset(escalator.pending_decision_ids())
        late = await escalator.receive_human_response(decision_id, dict(entry.response))
        resolved.add(decision_id)

        resolutions.append(
            Resolution(
                decision_id=decision_id,
                timed_out=entry.times_out,
                result=result,
                pending_before=pending_before,
                pending_after=pending_after,
                still_outstanding=all_ids - resolved,
                completed_others=frozenset(
                    other for other, task in tasks.items() if other != decision_id and task.done()
                ),
                expected_completed_others=frozenset(resolved - {decision_id}),
                response_accepted=accepted,
                late_response_accepted=late,
            ),
        )

    await asyncio.gather(*tasks.values(), return_exceptions=True)

    return DriveReport(
        registered=registered,
        resolutions=tuple(resolutions),
        pending_at_end=escalator.pending_decision_ids(),
        published=tuple(producer.published),
        reported_bounds=tuple(waiter.reported_bounds),
    )



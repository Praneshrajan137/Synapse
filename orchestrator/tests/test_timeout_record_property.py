"""Property-based test for honest HITL timeout records (task 8.10, design E3).

Feature: purpose-achievement-audit, Property 25: Timeout records match dispatch reality

    *For any* timeout action and *any* resolution ordering of concurrently outstanding
    escalations, ``human_override`` records a dispatched action only when a matching
    entry exists in ``execution_confirmations``, a timed-out escalation is resolved with
    no pending entry retained for its decision identifier, a response addressed to
    either outstanding identifier is accepted, and resolving one escalation dispatches
    nothing for the other.

Why the property is shaped this way
-----------------------------------

Requirement 5's secondary finding is an I-7 wording breach: ``EXECUTE_TIER1`` and
``EXECUTE_LAST_KNOWN_GOOD`` wrote ``human_override = {"action": "timeout_<name>"}`` while
``escalate`` only awaits a human future and dispatches nothing, so the audit row named an
action nobody performed. Task 8.9 made the claim *derived* instead of asserted:
``dispatched`` comes from the decision's own ``execution_confirmations`` through
``has_dispatch_confirmation``, and the requested fallback is named only when that evidence
exists. ``orchestrator/tests/test_escalation.py`` pins that at four examples. Three
failure modes survive any fixed set of examples:

1. **A fabricated dispatch.** The claim is correct for the examples chosen and wrong for
   some other evidence shape - a padded or upper-cased status, an ``error:`` entry
   alongside a real one, an absence status the vocabulary forgot. The property drives
   *sets* of evidence whose meaning is known from how each entry was generated, so a
   classifier that guesses is caught rather than agreed with.
2. **A leaked pending entry.** ``_resolve_pending`` runs in a ``finally``, so a single
   escalation always looks clean. What a single escalation cannot show is that resolving
   one removed *exactly* one entry: the property asserts the pending set before and after
   every resolution, so a removal that drops two entries, none, or the wrong one fails.
3. **Cross-talk between outstanding escalations.** The example test resolves two
   escalations in one fixed order. The property permutes the resolution order over two to
   four concurrent escalations and asserts, at each step, that no other escalation
   completed and that the pending set is exactly the identifiers not yet resolved.

Independent oracle
------------------

``dispatched`` is never checked against a re-run of the subject's own classifier. Every
generated confirmation entry is drawn from one of two vocabularies declared *here*:
``ABSENCE_STATUSES`` plus ``error:``-prefixed entries record an absence of enacted work,
and ``ENACTED_STATUSES`` record work an agent actually performed (the shapes
``_phase_execute`` writes: an agent's ``status`` field, ``no_result`` when a response
carried none, ``error:<exc>`` when the hop raised - ``protocol.py:1517``). The expected
verdict is therefore a property of *how the example was built*, and the subject is
compared against that provenance. Duplicating the absence vocabulary is deliberate: if a
status is dropped from the module's set, ``unknown`` starts counting as a dispatch, and
under I-7 that is exactly the regression this file must fail on.

``diverged`` is generated by neither pool. ``sustainability_agent`` returns it with empty
``world_effects``, which the audit credits as honest non-action, yet
``_NON_DISPATCH_CONFIRMATIONS`` does not list it - so a ``diverged`` confirmation would
currently read as an enacted dispatch. That is a live cross-cutting question for the
owner of ``escalation.py``; this property neither blesses nor condemns it, and says so
rather than encoding a guess.

Cost, and why this is not slow-marked
-------------------------------------

Every timeout is driven through the injected ``HumanResponseWaiter`` seam, gated on an
``asyncio.Event``: the configured bound is *reported* and never awaited, so no example
sleeps and the ordering of timeouts against human responses is generated rather than
raced. Completion is settled by a bounded number of scheduler turns, so a regression
fails instead of hanging - there is no watchdog and therefore no wall clock anywhere in
this file. Nothing here constructs ``ConsensusProtocol``, drives the SimPy twin, opens a
socket, or touches Postgres, so the test carries no ``@pytest.mark.slow`` and runs in
``ci.yml::quality-gates`` with the rest of ``orchestrator/tests``.

Async style
-----------

``orchestrator/tests/test_escalation.py`` drives ``escalate`` with plain ``asyncio`` -
``create_task``, ``receive_human_response``, and a scripted timer-free waiter. This file
drives that same shape. Hypothesis owns the test function, so each example enters the
loop through one ``asyncio.run`` call, which is what the repo's other async property
tests do (``orchestrator/tests/consensus/test_append_only_pbt.py:222``,
``test_debate_concession_pbt.py:283``). No new async framework, no event-loop fixture,
and no ``@given`` layered on ``@pytest.mark.asyncio`` under ``asyncio_mode = "strict"``.

Every timeout bound in this file comes from an ``OrchestratorConfig`` instance and the
generated range is derived from the configured default, so no seconds literal appears
here. ``max_examples`` is never set - the budget comes from the root ``conftest.py``
profiles (``dev``=10, ``heavy``=100, ``ci``/``default``=500, ``nightly``=5000).

**Validates: Requirements 5.5, 5.8, 5.9**
"""


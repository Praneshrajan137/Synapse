// ============================================================================
// SYNAPSE Chromatic System — token build (anti-corruption layer)
//
// Compiles the DTCG token JSON (the domain model) into four delivery
// artifacts. Deterministic: same JSON in -> byte-identical artifacts out
// (INV-CLR-010). Run via `npm run build` or `make tokens-build`.
// ============================================================================
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { loadTokens, resolveAll, num } from "./resolve.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const DIST = join(ROOT, "dist");
const VERSION = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).version;

const TOKEN_FILES = [
  join(ROOT, "tokens", "primitives.tokens.json"),
  join(ROOT, "tokens", "agents.tokens.json"),
  join(ROOT, "tokens", "semantic.tokens.json"),
];

// Only these top-level groups are emitted as runtime artifacts. `ref.*`
// primitives are build-time only (three-tier token architecture).
const EMIT_PREFIXES = ["color.", "motion.", "radius."];
const isEmitted = (path) => EMIT_PREFIXES.some((p) => path.startsWith(p));

const cssVar = (path) => `--${path.replace(/\./g, "-")}`;
const banner = "/* GENERATED by design-system/color/build/build.mjs — DO NOT EDIT. */";

/** Build the resolved model and the emitted token list (sorted, deterministic). */
function model() {
  const flat = loadTokens(TOKEN_FILES);
  const resolved = resolveAll(flat);
  const paths = [...resolved.light.keys()].filter(isEmitted).sort();
  return { resolved, paths };
}

/** Confidence diverging stops, keyed by gate position (I-5). */
function confidenceStops(resolved, theme) {
  const at = (k) => resolved[theme].get(`color.confidence.${k}`).oklch;
  return [
    { pos: 0.0, key: "low", ...at("low") },
    { pos: 0.7, key: "escalation", ...at("escalation") },
    { pos: 0.8, key: "autonomous", ...at("autonomous") },
    { pos: 1.0, key: "peak", ...at("peak") },
  ];
}

function confidenceGradient(resolved, theme) {
  const css = (k) => resolved[theme].get(`color.confidence.${k}`).css;
  return `linear-gradient(90deg, ${css("low")} 0%, ${css("escalation")} 70%, ${css("autonomous")} 80%, ${css("peak")} 100%)`;
}

function tierGradient(resolved, theme) {
  const css = (n) => resolved[theme].get(`color.tier.${n}`).css;
  return `linear-gradient(90deg, ${css(1)} 0%, ${css(2)} 33%, ${css(3)} 66%, ${css(4)} 100%)`;
}

// --- tokens.css -------------------------------------------------------------
function emitCss({ resolved, paths }) {
  const colorVars = (theme) =>
    paths
      .filter((p) => resolved[theme].get(p).type === "color")
      .map((p) => `  ${cssVar(p)}: ${resolved[theme].get(p).css};`)
      .join("\n");

  const scalarVars = paths
    .filter((p) => resolved.light.get(p).type !== "color")
    .map((p) => `  ${cssVar(p)}: ${resolved.light.get(p).value};`)
    .join("\n");

  const hexFallback = (theme) =>
    paths
      .filter((p) => resolved[theme].get(p).type === "color")
      .map((p) => `    ${cssVar(p)}: ${resolved[theme].get(p).hex};`)
      .join("\n");

  return `${banner}
/* SYNAPSE Chromatic System v${VERSION} — OKLCH design tokens.
 * Default theme: dark (operators run in low-ambient control rooms).
 * Author in OKLCH; older engines fall back to sRGB hex via @supports. */

:root,
[data-theme="light"] {
${colorVars("light")}

  /* scalar tokens (theme-agnostic) */
${scalarVars}

  /* composite gradients */
  --gradient-confidence: ${confidenceGradient(resolved, "light")};
  --gradient-tier: ${tierGradient(resolved, "light")};
  color-scheme: light;
}

[data-theme="dark"] {
${colorVars("dark")}

  --gradient-confidence: ${confidenceGradient(resolved, "dark")};
  --gradient-tier: ${tierGradient(resolved, "dark")};
  color-scheme: dark;
}

/* Auto dark when no explicit theme is set and the OS prefers dark. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorVars("dark")}
    --gradient-confidence: ${confidenceGradient(resolved, "dark")};
    --gradient-tier: ${tierGradient(resolved, "dark")};
    color-scheme: dark;
  }
}

/* Base surface. */
html {
  background-color: var(--color-surface-canvas);
  color: var(--color-text-primary);
}

/* Focus ring — never removed without a visible alternative (INV-CLR-013). */
:focus-visible {
  outline: 2px solid var(--color-focus-ring);
  outline-offset: 2px;
  border-radius: 2px;
}

/* Reduced motion — disable non-essential animation (INV-CLR-013). */
@media (prefers-reduced-motion: reduce) {
  *,
  *::before,
  *::after {
    animation-duration: 0.001ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.001ms !important;
    scroll-behavior: auto !important;
  }
}

/* Increased contrast — strengthen borders + drop low-emphasis text a tier. */
@media (prefers-contrast: more) {
  :root,
  [data-theme="light"] {
    --color-border-subtle: var(--color-border-strong);
    --color-text-tertiary: var(--color-text-secondary);
  }
  [data-theme="dark"] {
    --color-border-subtle: var(--color-border-strong);
    --color-text-tertiary: var(--color-text-secondary);
  }
}

/* Windows high-contrast — defer to system colours (INV-CLR-013). */
@media (forced-colors: active) {
  :focus-visible {
    outline: 2px solid Highlight;
  }
}

/* sRGB fallback for engines without OKLCH support (pre-2023). */
@supports not (color: oklch(0 0 0)) {
  :root,
  [data-theme="light"] {
${hexFallback("light")}
  }
  [data-theme="dark"] {
${hexFallback("dark")}
  }
}
`;
}

// --- tokens.ts --------------------------------------------------------------
function emitTs({ resolved, paths }) {
  const colorPaths = paths.filter((p) => resolved.light.get(p).type === "color");
  const entries = colorPaths
    .map((p) => {
      const l = resolved.light.get(p);
      const d = resolved.dark.get(p);
      const key = JSON.stringify(p);
      return `  ${key}: { cssVar: "var(${cssVar(p)})", light: ${JSON.stringify(l.hex)}, dark: ${JSON.stringify(d.hex)}, lightRgb: ${JSON.stringify(l.rgb255)}, darkRgb: ${JSON.stringify(d.rgb255)} },`;
    })
    .join("\n");

  const stops = (theme) =>
    JSON.stringify(confidenceStops(resolved, theme).map((s) => ({ pos: s.pos, l: s.l, c: s.c, h: s.h })));

  return `${banner}
// SYNAPSE Chromatic System v${VERSION} — typed token API.
// Consumed by React components and by deck.gl / MapLibre / force-graph
// (which need [r,g,b] arrays rather than CSS strings).

export type Theme = "light" | "dark";

export interface ColorToken {
  readonly cssVar: string;
  readonly light: string;
  readonly dark: string;
  readonly lightRgb: readonly [number, number, number];
  readonly darkRgb: readonly [number, number, number];
}

export const tokens: Record<string, ColorToken> = {
${entries}
};

export const AGENTS = [
  "demand-prophet",
  "routing-navigator",
  "inventory-sentinel",
  "freshness-guardian",
  "pricing-oracle",
  "disruption-shield",
  "supplier-trust",
  "sustainability-agent",
] as const;
export type AgentKey = (typeof AGENTS)[number];

/** CSS custom-property reference for an agent identity colour. */
export function agentVar(agent: string): string {
  return "var(--color-agent-" + agent.replace(/_/g, "-") + ")";
}

/** [r,g,b] 0-255 array for an agent — for deck.gl / three / force-graph. */
export function agentRgb(agent: string, theme: Theme = "dark"): readonly [number, number, number] {
  const t = tokens["color.agent." + agent.replace(/_/g, "-")];
  if (!t) throw new Error("unknown agent: " + agent);
  return theme === "dark" ? t.darkRgb : t.lightRgb;
}

/** [r,g,b] 0-255 array for a decision tier (1-4). */
export function tierRgb(tier: number, theme: Theme = "dark"): readonly [number, number, number] {
  const t = tokens["color.tier." + tier];
  if (!t) throw new Error("unknown tier: " + tier);
  return theme === "dark" ? t.darkRgb : t.lightRgb;
}

const CONFIDENCE_STOPS: Record<Theme, ReadonlyArray<{ pos: number; l: number; c: number; h: number }>> = {
  light: ${stops("light")},
  dark: ${stops("dark")},
};

/**
 * Continuous confidence colour for value in [0,1], interpolated piecewise in
 * OKLCH across the gate-anchored stops (0.00 / 0.70 / 0.80 / 1.00). Returns an
 * oklch() CSS string. Hue is monotonic, so direct OKLCH lerp is well-defined.
 */
export function confidenceColor(value: number, theme: Theme = "dark"): string {
  const v = Math.min(1, Math.max(0, value));
  const stops = CONFIDENCE_STOPS[theme];
  let a = stops[0];
  let b = stops[stops.length - 1];
  for (let i = 0; i < stops.length - 1; i++) {
    if (v >= stops[i].pos && v <= stops[i + 1].pos) {
      a = stops[i];
      b = stops[i + 1];
      break;
    }
  }
  const span = b.pos - a.pos || 1;
  const t = (v - a.pos) / span;
  const lerp = (x: number, y: number) => x + (y - x) * t;
  const round = (x: number, d: number) => Number(x.toFixed(d));
  return (
    "oklch(" +
    round(lerp(a.l, b.l), 4) +
    " " +
    round(lerp(a.c, b.c), 4) +
    " " +
    round(lerp(a.h, b.h), 2) +
    ")"
  );
}

/** I-5 confidence gate thresholds. */
export const CONFIDENCE_GATE = { low: 0.7, high: 0.8 } as const;

/** Confidence zone for a value — drives non-colour signals (INV-CLR-011). */
export function confidenceZone(value: number): "low" | "escalation" | "autonomous" {
  if (value < CONFIDENCE_GATE.low) return "low";
  if (value < CONFIDENCE_GATE.high) return "escalation";
  return "autonomous";
}
`;
}

// --- tailwind-preset.cjs ----------------------------------------------------
function emitTailwind({ resolved, paths }) {
  const colorPaths = paths.filter(
    (p) => resolved.light.get(p).type === "color" && p.startsWith("color."),
  );
  const tree = {};
  for (const p of colorPaths) {
    const parts = p.split(".").slice(1); // drop "color"
    let node = tree;
    for (let i = 0; i < parts.length - 1; i++) {
      node[parts[i]] = node[parts[i]] || {};
      node = node[parts[i]];
    }
    const leaf = parts[parts.length - 1];
    node[parts.length === 1 ? "DEFAULT" : leaf] = `var(${cssVar(p)})`;
  }
  return `${banner}
// SYNAPSE Chromatic System v${VERSION} — Tailwind preset.
// Bind utilities to CSS custom properties so a single class flips across
// [data-theme]. Transparency/tint uses color-mix() in component CSS, not
// opacity modifiers (the vars hold full oklch() colours, not channels).
module.exports = {
  theme: {
    extend: {
      colors: ${JSON.stringify(tree, null, 6).replace(/\n/g, "\n      ")},
      borderRadius: {
        sm: "var(--radius-sm)",
        md: "var(--radius-md)",
        lg: "var(--radius-lg)",
        xl: "var(--radius-xl)",
      },
      transitionTimingFunction: {
        standard: "var(--motion-ease-standard)",
        decelerate: "var(--motion-ease-decelerate)",
        emphasized: "var(--motion-ease-emphasized)",
      },
      transitionDuration: {
        fast: "var(--motion-duration-fast)",
        base: "var(--motion-duration-base)",
        slow: "var(--motion-duration-slow)",
      },
      backgroundImage: {
        "gradient-confidence": "var(--gradient-confidence)",
        "gradient-tier": "var(--gradient-tier)",
      },
    },
  },
};
`;
}

// --- tokens.json (flat resolved map — tests + contrast report) --------------
function emitJson({ resolved, paths }) {
  const out = {};
  for (const p of paths) {
    const l = resolved.light.get(p);
    const d = resolved.dark.get(p);
    if (l.type === "color") {
      out[p] = {
        type: "color",
        light: { oklch: l.oklch, css: l.css, hex: l.hex, rgb255: l.rgb255 },
        dark: { oklch: d.oklch, css: d.css, hex: d.hex, rgb255: d.rgb255 },
      };
    } else {
      out[p] = { type: l.type, value: l.value };
    }
  }
  return JSON.stringify({ $generated: "build.mjs", version: VERSION, tokens: out }, null, 2) + "\n";
}

function build() {
  const m = model();
  mkdirSync(DIST, { recursive: true });
  const artifacts = {
    "tokens.css": emitCss(m),
    "tokens.ts": emitTs(m),
    "tailwind-preset.cjs": emitTailwind(m),
    "tokens.json": emitJson(m),
  };
  for (const [name, content] of Object.entries(artifacts)) {
    writeFileSync(join(DIST, name), content, "utf8");
  }
  return Object.keys(artifacts);
}

const written = build();
process.stdout.write(`chromatic build OK — ${written.join(", ")}\n`);

export { build, model, confidenceStops };
